"""Write the example cell's URDFs (run from anywhere; overwrites them).

* ``assets/arm_gripper.urdf``: the TM5S arm of ``cells/tm_tray`` (its URDF and
  meshes, reused unchanged) with a simple parallel gripper on the flange, made of
  boxes: a body, two fingers on prismatic joints, and a ``tcp`` frame between the
  fingers. Joint value ``q`` of a finger = its inner face's distance from the tcp
  axis, so the opening is ``2 q``.
* ``assets/block.usda``: the object, as USD (a model can be a URDF or a USD file): a
  ``Cube`` scaled to the block's size, marked as a collider, with its mass and an orange
  material (Isaac shows it; docs/cell_model.md, Looks); the part's
  frame (``/block``) is at the centre of its underside, so it stands on a feature
  without an offset. Written as plain text, so it needs no USD library.

The numbers are the ``GRIPPER`` and ``BLOCK`` constants below; the plugin reads
them back from the URDFs (``plugin/example_pick_place/geometry.py``), nothing is
copied by hand.

    python cells/example_pick_place/tools/make_assets.py
"""
from __future__ import annotations

import os
from pathlib import Path

CELL = Path(__file__).resolve().parents[1]
ARM = CELL.parent / "tm_tray" / "assets" / "tm5s" / "tm5s.urdf"

GRIPPER = {
    "body": (0.12, 0.05, 0.04),       # x (finger travel) y z (along the approach), on the flange
    "body_mass": 0.5,
    "finger": (0.01, 0.02, 0.06),     # one finger: x (thickness) y (width) z (length)
    "finger_mass": 0.05,
    "finger_root_z": 0.04,            # where the fingers start (the body's far face)
    "stroke": (0.0, 0.05),            # finger joint limits (inner face from the axis)
    "tcp_z": 0.08,                    # tcp on the flange axis, 20 mm from the finger tips
    "force": 100.0,                   # N per finger
}
BLOCK = {"size": (0.04, 0.04, 0.06), "mass": 0.2}


def _box(name, size, xyz=(0, 0, 0)):
    s = " ".join(f"{v:g}" for v in size)
    o = " ".join(f"{v:g}" for v in xyz)
    return (f'    <visual name="{name}"><origin xyz="{o}"/><geometry><box size="{s}"/></geometry></visual>\n'
            f'    <collision name="{name}"><origin xyz="{o}"/><geometry><box size="{s}"/></geometry></collision>\n')


def _inertial(m, size):
    x, y, z = size
    i = [m / 12 * (y * y + z * z), m / 12 * (x * x + z * z), m / 12 * (x * x + y * y)]
    return (f'    <inertial><mass value="{m:g}"/>'
            f'<inertia ixx="{i[0]:.3e}" ixy="0" ixz="0" iyy="{i[1]:.3e}" iyz="0" izz="{i[2]:.3e}"/></inertial>\n')


def gripper_xml() -> str:
    g = GRIPPER
    bx, by, bz = g["body"]
    fx, fy, fz = g["finger"]
    root = g["finger_root_z"]
    lo, hi = g["stroke"]
    out = ['  <!-- example parallel gripper (cells/example_pick_place/tools/make_assets.py) -->\n',
           '  <link name="gripper_body">\n', _inertial(g["body_mass"], g["body"]),
           _box("body", g["body"], (0, 0, bz / 2)), '  </link>\n',
           '  <joint name="gripper_fixed" type="fixed"><parent link="flange"/><child link="gripper_body"/></joint>\n']
    for side, sign in (("right", 1), ("left", -1)):
        out += [f'  <link name="finger_{side}">\n', _inertial(g["finger_mass"], g["finger"]),
                _box(f"finger_{side}", g["finger"], (sign * fx / 2, 0, fz / 2)), '  </link>\n',
                f'  <joint name="finger_{side}_joint" type="prismatic">\n'
                f'    <parent link="gripper_body"/><child link="finger_{side}"/>\n'
                f'    <origin xyz="0 0 {root:g}"/><axis xyz="{sign} 0 0"/>\n'
                f'    <limit lower="{lo:g}" upper="{hi:g}" effort="{g["force"]:g}" velocity="0.1"/>\n'
                '  </joint>\n']
    out += ['  <link name="tcp"/>\n',
            f'  <joint name="tcp_fixed" type="fixed"><parent link="gripper_body"/><child link="tcp"/>'
            f'<origin xyz="0 0 {g["tcp_z"]:g}"/></joint>\n']
    return "".join(out)


def main() -> None:
    assets = CELL / "assets"
    assets.mkdir(exist_ok=True)
    mesh_dir = os.path.relpath(ARM.parent / "meshes", assets)
    arm = ARM.read_text().replace('filename="meshes/', f'filename="{mesh_dir}/')
    arm = arm.replace('<robot name="tm5s">', '<robot name="tm5s_example_gripper">')
    head = ("<!-- Generated by cells/example_pick_place/tools/make_assets.py: the TM5S of cells/tm_tray "
            "with a box parallel gripper. Do not edit; change the script. -->\n")
    xml = arm.replace("</robot>", gripper_xml() + "</robot>")
    xml = xml.replace("<robot ", head + "<robot ", 1) if xml.startswith("<robot") else xml.replace(
        "?>\n", "?>\n" + head, 1)
    (assets / "arm_gripper.urdf").write_text(xml)
    (assets / "block.usda").write_text(block_usda())
    print(f"wrote {assets / 'arm_gripper.urdf'} and {assets / 'block.usda'}")


def block_usda() -> str:
    x, y, z = BLOCK["size"]
    return f"""#usda 1.0
(
    doc = "Generated by cells/example_pick_place/tools/make_assets.py"
    defaultPrim = "block"
    metersPerUnit = 1
    kilogramsPerUnit = 1
    upAxis = "Z"
)

def Xform "block" (
    prepend apiSchemas = ["PhysicsMassAPI"]
)
{{
    float physics:mass = {BLOCK["mass"]:g}

    def Scope "Looks"
    {{
        def Material "orange"
        {{
            token outputs:surface.connect = </block/Looks/orange/pbr.outputs:surface>

            def Shader "pbr"
            {{
                uniform token info:id = "UsdPreviewSurface"
                color3f inputs:diffuseColor = (0.93, 0.55, 0.15)
                float inputs:roughness = 0.45
                token outputs:surface
            }}
        }}
    }}

    def Cube "body" (
        prepend apiSchemas = ["PhysicsCollisionAPI", "MaterialBindingAPI"]
    )
    {{
        rel material:binding = </block/Looks/orange>
        double size = 1
        double3 xformOp:translate = (0, 0, {z / 2:g})
        float3 xformOp:scale = ({x:g}, {y:g}, {z:g})
        uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:scale"]
    }}
}}
"""


if __name__ == "__main__":
    main()
